#!/usr/bin/env node
// Materialises db/migrations/0001_new_lead_alert_outbox.{up,down}.sql VERBATIM from the SQL
// fences of docs/NEW_LEAD_ALERT_OUTBOX_DDL_REVIEW.md.
//
// The document is the source of truth. This script exists so that "the migration file matches
// the reviewed design" is a re-runnable proof rather than a claim: re-run it and `git diff`
// must be empty. Do NOT hand-edit the generated .sql files -- edit the document.
//
// Fences are located by SECTION HEADING, not by line number, so editing the prose around them
// cannot silently re-map the migration.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOC = path.join(ROOT, 'docs', 'NEW_LEAD_ALERT_OUTBOX_DDL_REVIEW.md');
const OUT = path.join(ROOT, 'db', 'migrations');

// heading prefix -> how many consecutive ```sql fences under it belong to the migration
const FORWARD = ['### 4.1', '### 4.2', '### 4.3', '### 4.4', '### 4.5', '### 4.6', '### 4.7'];
const ROLLBACK = ['## 5.'];

const lines = fs.readFileSync(DOC, 'utf8').split(/\r?\n/);

function fenceUnder(headingPrefix) {
  const start = lines.findIndex((l) => l.startsWith(headingPrefix));
  if (start === -1) throw new Error(`heading not found: ${headingPrefix}`);
  for (let i = start + 1; i < lines.length; i++) {
    if (/^#{2,3} /.test(lines[i])) break;             // ran into the next section
    if (lines[i] === '```sql') {
      const close = lines.indexOf('```', i + 1);
      if (close === -1) throw new Error(`unterminated sql fence under ${headingPrefix}`);
      return lines.slice(i + 1, close).join('\n');
    }
  }
  throw new Error(`no sql fence under ${headingPrefix}`);
}

const header = (title) => `-- ============================================================================
-- ${title}
-- SOURCE OF TRUTH: docs/NEW_LEAD_ALERT_OUTBOX_DDL_REVIEW.md
-- This file is a VERBATIM materialisation of the SQL fences in that document.
-- Generated by db/validation/extract-migration.mjs -- do not hand-edit.
-- ============================================================================
`;

fs.writeFileSync(path.join(OUT, '0001_new_lead_alert_outbox.up.sql'),
  header('FINMENTOR NEW LEAD ALERT OUTBOX - forward migration (doc sections 4.1-4.7)')
  + FORWARD.map(fenceUnder).join('\n\n') + '\n');
fs.writeFileSync(path.join(OUT, '0001_new_lead_alert_outbox.down.sql'),
  header('FINMENTOR NEW LEAD ALERT OUTBOX - rollback (doc section 5)')
  + ROLLBACK.map(fenceUnder).join('\n\n') + '\n');
console.log('materialised 0001_new_lead_alert_outbox.{up,down}.sql');
