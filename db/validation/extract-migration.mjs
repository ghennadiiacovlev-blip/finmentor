#!/usr/bin/env node
// Materialises db/migrations/*.sql VERBATIM from the SQL fences of the design documents.
//
// The documents are the source of truth. This script exists so that "the migration file matches
// the reviewed design" is a re-runnable proof rather than a claim: re-run it and `git diff`
// must be empty. Do NOT hand-edit the generated .sql files -- edit the document.
//
// Fences are located by SECTION HEADING, not by line number, so editing the prose around them
// cannot silently re-map the migration.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'db', 'migrations');

// Each entry: the source document, and for the forward and rollback files, the section headings
// whose FIRST ```sql fence belongs to that file, in order.
const MIGRATIONS = [
  {
    doc: 'docs/NEW_LEAD_ALERT_OUTBOX_DDL_REVIEW.md',
    base: '0001_new_lead_alert_outbox',
    up: { title: 'FINMENTOR NEW LEAD ALERT OUTBOX - forward migration (doc sections 4.1-4.7)',
          headings: ['### 4.1', '### 4.2', '### 4.3', '### 4.4', '### 4.5', '### 4.6', '### 4.7'] },
    down: { title: 'FINMENTOR NEW LEAD ALERT OUTBOX - rollback (doc section 5)',
            headings: ['## 5.'] },
  },
  {
    doc: 'docs/TELEGRAM_DURABLE_NEW_LEAD_DELIVERY_PLAN.md',
    base: '0002_alerts_runtime_logins',
    up: { title: 'FINMENTOR ALERTS RUNTIME LOGINS - forward migration (doc sections 2.3-2.4)',
          headings: ['### 2.3', '### 2.4'] },
    down: { title: 'FINMENTOR ALERTS RUNTIME LOGINS - rollback (doc section 2.7)',
            headings: ['### 2.7'] },
  },
];

function fenceUnder(lines, headingPrefix, doc) {
  const start = lines.findIndex((l) => l.startsWith(headingPrefix));
  if (start === -1) throw new Error(`heading not found in ${doc}: ${headingPrefix}`);
  for (let i = start + 1; i < lines.length; i++) {
    if (/^#{2,3} /.test(lines[i])) break;             // ran into the next section
    if (lines[i] === '```sql') {
      const close = lines.indexOf('```', i + 1);
      if (close === -1) throw new Error(`unterminated sql fence under ${headingPrefix}`);
      return lines.slice(i + 1, close).join('\n');
    }
  }
  throw new Error(`no sql fence under ${headingPrefix} in ${doc}`);
}

const header = (title, doc) => `-- ============================================================================
-- ${title}
-- SOURCE OF TRUTH: ${doc}
-- This file is a VERBATIM materialisation of the SQL fences in that document.
-- Generated by db/validation/extract-migration.mjs -- do not hand-edit.
-- ============================================================================
`;

for (const m of MIGRATIONS) {
  const lines = fs.readFileSync(path.join(ROOT, m.doc), 'utf8').split(/\r?\n/);
  for (const [kind, spec] of [['up', m.up], ['down', m.down]]) {
    fs.writeFileSync(path.join(OUT, `${m.base}.${kind}.sql`),
      header(spec.title, m.doc)
      + spec.headings.map((h) => fenceUnder(lines, h, m.doc)).join('\n\n') + '\n');
  }
  console.log(`materialised ${m.base}.{up,down}.sql`);
}
